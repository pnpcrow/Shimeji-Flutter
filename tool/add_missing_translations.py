# Catalan ships an untranslated English value for Scaling; fix it in place.
OVERRIDE = {
    'language_ca.properties': {'Scaling': 'Escalat'},
}

HEADER = '# Shimeji Flutter - settings screen and behaviour group labels'


def existing_keys(text):
    keys = set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith('#') or line.startswith('!'):
            continue
        sep = line.find('=')
        if sep < 0:
            sep = line.find(':')
        if sep >= 0:
            keys.add(line[:sep].strip())
    return keys


def main():
    for name, additions in ADD.items():
        if additions is None:
            additions = ADD['language.properties']
        path = os.path.join(CONF, name)
        with io.open(path, 'r', encoding='utf-8') as fh:
            text = fh.read()
        have = existing_keys(text)
        missing = {k: v for k, v in additions.items() if k not in have}
        for key, value in OVERRIDE.get(name, {}).items():
            # Replace an untranslated value in place.
            lines = text.splitlines()
            for i, line in enumerate(lines):
                if line.startswith(key + '='):
                    lines[i] = '%s=%s' % (key, value)
                    break
            text = '\n'.join(lines) + '\n'
        if missing:
            if not text.endswith('\n'):
                text += '\n'
            text += '\n%s\n' % HEADER
            for key, value in missing.items():
                text += '%s=%s\n' % (key, value)
            with io.open(path, 'w', encoding='utf-8', newline='\n') as fh:
                fh.write(text)
            print('%s: +%d keys' % (name, len(missing)))
        else:
            print('%s: up to date' % name)


if __name__ == '__main__':
    main()
